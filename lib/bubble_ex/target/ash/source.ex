defmodule BubbleEx.Target.Ash.Source do
  @moduledoc """
  Prints a `BubbleEx.Target.Ash.Project` as one Elixir source file: the
  enum and typed-struct modules, one `Ash.Resource` per resource (AshPostgres
  data layer) and an `Ash.Domain` listing them.

      {:ok, project} = BubbleEx.Target.Ash.map(model)
      {:ok, source} = BubbleEx.Target.Ash.Source.render(project, namespace: "MyApp")

  The renderer only prints. Every mapping decision is already in the
  Project; this module never looks at Bubble or `BubbleEx.Model` types (a
  `mix xref` test enforces it). It chooses only the root namespace, the
  domain and the repo. The output is run through the Elixir formatter.

  ## Options

    * `:namespace` - root namespace of the generated modules, default
      `"MyApp"`
    * `:domain` - the `Ash.Domain` module, default the namespace
    * `:repo` - the AshPostgres repo module, default `"<namespace>.Repo"`.
      It is referenced, not generated.
  """

  alias BubbleEx.Error
  alias BubbleEx.Target.Ash.{Attribute, Project, Relationship, Resource, TypedStruct}

  @alias ~r/^[A-Z][A-Za-z0-9_]*(\.[A-Z][A-Za-z0-9_]*)*$/
  @identifier ~r/^[a-z_][A-Za-z0-9_]*[?!]?$/

  @locals_without_parens [
    table: 1,
    repo: 1,
    reference: 2,
    attribute: 2,
    attribute: 3,
    belongs_to: 2,
    belongs_to: 3,
    source_attribute: 1,
    destination_attribute: 1,
    attribute_type: 1,
    define_attribute?: 1,
    allow_nil?: 1,
    public?: 1,
    identity: 2,
    identity: 3,
    defaults: 1,
    resource: 1,
    field: 2,
    field: 3
  ]

  @header """
  # Generated by bubble_ex from a Bubble app's data model. Deterministic:
  # the same model and name map give the same file.
  #
  # One file holds many modules; split them one per file in your project
  # (lib/my_app/task.ex, ...). The repo is referenced but not generated:
  #   mix igniter.new my_app --install ash,ash_postgres
  # then add these modules and run `mix ash.codegen --dev` while iterating.
  """

  @type option :: {:namespace, String.t()} | {:domain, String.t()} | {:repo, String.t()}

  @doc "Renders `project` as formatted Elixir source."
  @spec render(Project.t(), [option()]) :: {:ok, String.t()} | {:error, Error.t()}
  def render(project, opts \\ [])

  def render(%Project{} = project, opts) when is_list(opts) do
    namespace = Keyword.get(opts, :namespace, "MyApp")
    domain = Keyword.get(opts, :domain, namespace)
    repo = Keyword.get(opts, :repo, namespace <> ".Repo")

    with :ok <- check_alias(:namespace, namespace),
         :ok <- check_alias(:domain, domain),
         :ok <- check_alias(:repo, repo) do
      ctx = %{namespace: namespace, domain: domain, repo: repo}

      modules =
        Enum.map(project.enums, &enum(&1, ctx)) ++
          Enum.map(project.typed_structs, &typed_struct(&1, ctx)) ++
          Enum.map(project.resources, &resource(&1, ctx)) ++
          [domain_module(project, ctx)]

      source = @header <> "\n" <> Enum.join(modules, "\n\n")

      formatted =
        source
        |> Code.format_string!(locals_without_parens: @locals_without_parens)
        |> IO.iodata_to_binary()

      {:ok, formatted <> "\n"}
    end
  end

  def render(_project, _opts),
    do: {:error, Error.new(:invalid_input, "expected a BubbleEx.Target.Ash.Project")}

  defp check_alias(option, value) do
    if is_binary(value) and Regex.match?(@alias, value),
      do: :ok,
      else:
        {:error, Error.new(:invalid_input, "#{option} must be a module name", %{option => value})}
  end

  # --- modules -------------------------------------------------------------------

  defp enum(enum, ctx) do
    values = Enum.map_join(enum.values, ", ", &enum_value/1)

    lookup =
      if enum.attributes == [] do
        ""
      else
        entries =
          Enum.map_join(enum.values, ", ", fn value ->
            fields =
              Enum.map_join(enum.attributes, ", ", fn attribute ->
                key(attribute.name) <> literal(Map.get(value.attributes, attribute.name))
              end)

            literal(value.value) <> " => %{" <> fields <> "}"
          end)

        """

        @attributes %{#{entries}}

        @doc "The attribute values of `value`."
        def attributes(value), do: Map.fetch!(@attributes, value)
        """
      end

    """
    defmodule #{module(enum.module, ctx)} do
      #{moduledoc(enum.description)}use Ash.Type.Enum, values: [#{values}]
    #{lookup}end
    """
  end

  defp enum_value(%{label: nil, value: value}), do: literal(value)

  defp enum_value(%{label: label, value: value}),
    do: "{#{literal(value)}, [label: #{literal(label)}]}"

  defp typed_struct(%TypedStruct{} = struct, ctx) do
    fields = Enum.map_join(struct.fields, "\n", &field(&1, ctx))

    """
    defmodule #{module(struct.module, ctx)} do
      #{moduledoc(struct.description)}use Ash.TypedStruct

      typed_struct do
    #{fields}
      end
    end
    """
  end

  defp field(%Attribute{} = attribute, ctx) do
    options =
      [{"allow_nil?", literal(attribute.allow_nil?)}] ++
        default(attribute) ++ constraints(attribute)

    "field #{atom(attribute.name)}, #{type(attribute.type, ctx)}, #{options(options)}"
  end

  defp resource(%Resource{} = resource, ctx) do
    """
    defmodule #{module(resource.module, ctx)} do
      #{moduledoc(resource.description)}use Ash.Resource, domain: #{ctx.domain}, data_layer: AshPostgres.DataLayer

      postgres do
        table #{literal(resource.table)}
        repo #{ctx.repo}
    #{references(resource.relationships)}
      end

      attributes do
    #{Enum.map_join(resource.attributes, "\n", &attribute(&1, ctx))}
      end
    #{relationships(resource.relationships, ctx)}#{identities(resource.identities)}
      actions do
        defaults #{literal(resource.actions)}
      end
    end
    """
  end

  defp attribute(%Attribute{} = attribute, ctx) do
    options =
      if(attribute.primary_key?, do: [{"primary_key?", "true"}], else: []) ++
        [
          {"allow_nil?", literal(attribute.allow_nil?)},
          {"writable?", literal(attribute.writable?)},
          {"public?", literal(attribute.public?)}
        ] ++ default(attribute) ++ constraints(attribute)

    "attribute #{atom(attribute.name)}, #{type(attribute.type, ctx)}, #{options(options)}"
  end

  defp default(%Attribute{default: {:value, value}}), do: [{"default", literal(value)}]
  defp default(%Attribute{}), do: []

  defp constraints(%Attribute{constraints: []}), do: []
  defp constraints(%Attribute{constraints: c}), do: [{"constraints", literal(c)}]

  defp options(options), do: Enum.map_join(options, ", ", fn {k, v} -> "#{k}: #{v}" end)

  defp references(relationships) do
    case Enum.filter(relationships, &(&1.db_reference == :ignore)) do
      [] ->
        ""

      ignored ->
        lines = Enum.map_join(ignored, "\n", &"reference #{atom(&1.name)}, ignore?: true")
        "\nreferences do\n#{lines}\nend"
    end
  end

  defp relationships([], _ctx), do: ""

  defp relationships(relationships, ctx) do
    "\nrelationships do\n" <>
      Enum.map_join(relationships, "\n\n", &relationship(&1, ctx)) <> "\nend\n"
  end

  defp relationship(%Relationship{} = r, ctx) do
    """
    #{r.kind} #{atom(r.name)}, #{module(r.destination, ctx)} do
      source_attribute #{atom(r.source_attribute)}
      destination_attribute #{atom(r.destination_attribute)}
      attribute_type #{type(r.attribute_type, ctx)}
      define_attribute? #{literal(r.define_attribute?)}
      allow_nil? #{literal(r.allow_nil?)}
      public? #{literal(r.public?)}
    end
    """
  end

  defp identities([]), do: ""

  defp identities(identities) do
    lines =
      Enum.map_join(identities, "\n", fn identity ->
        "identity #{atom(identity.name)}, [#{Enum.map_join(identity.keys, ", ", &atom/1)}]"
      end)

    "\nidentities do\n#{lines}\nend\n"
  end

  defp domain_module(project, ctx) do
    resources = Enum.map_join(project.resources, "\n", &"resource #{module(&1.module, ctx)}")

    """
    defmodule #{ctx.domain} do
      use Ash.Domain

      resources do
    #{resources}
      end
    end
    """
  end

  # --- printing --------------------------------------------------------------------

  defp moduledoc(nil), do: ""
  defp moduledoc(text), do: "@moduledoc #{literal(text)}\n\n"

  defp module(relative, ctx), do: ctx.namespace <> "." <> relative

  defp type({:array, type}, ctx), do: "{:array, #{type(type, ctx)}}"
  defp type({:module, relative}, ctx), do: module(relative, ctx)
  defp type(atom, _ctx) when is_atom(atom), do: inspect(atom)

  defp atom(name) do
    if Regex.match?(@identifier, name), do: ":" <> name, else: ":" <> literal(name)
  end

  defp key(name) do
    if Regex.match?(@identifier, name), do: name <> ": ", else: literal(name) <> ": "
  end

  defp literal(value), do: inspect(value, limit: :infinity, printable_limit: :infinity)
end
