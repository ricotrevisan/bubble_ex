defmodule BubbleEx.Target.Ash.Source do
  @moduledoc """
  Prints a `BubbleEx.Target.Ash.Project` as one Elixir source file: the
  enum and typed-struct modules, one `Ash.Resource` per resource (AshPostgres
  data layer) and an `Ash.Domain` listing them.

      {:ok, project} = BubbleEx.Target.Ash.map(model)
      {:ok, source} = BubbleEx.Target.Ash.Source.render(project, namespace: "MyApp")

  The renderer only prints. Every mapping decision is already in the
  Project; this module never looks at Bubble or `BubbleEx.Model` types (a
  `mix xref` test enforces it). It chooses only the root namespace, the
  domain and the repo. The output is run through the Elixir formatter.

  ## Options

    * `:namespace` - root namespace of the generated modules, default
      `"MyApp"`
    * `:domain` - the `Ash.Domain` module, default the namespace
    * `:repo` - the AshPostgres repo module, default `"<namespace>.Repo"`.
      It is referenced, not generated.
  """

  alias BubbleEx.Error

  alias BubbleEx.Target.Ash.{
    Action,
    Attribute,
    Calculation,
    CustomType,
    Expr,
    FieldPolicy,
    Policy,
    PolicyCheck,
    Project,
    Relationship,
    Resource,
    TypedStruct
  }

  @alias ~r/^[A-Z][A-Za-z0-9_]*(\.[A-Z][A-Za-z0-9_]*)*$/
  @identifier ~r/^[a-z_][A-Za-z0-9_]*[?!]?$/

  @locals_without_parens [
    table: 1,
    repo: 1,
    reference: 2,
    attribute: 2,
    attribute: 3,
    belongs_to: 2,
    belongs_to: 3,
    source_attribute: 1,
    destination_attribute: 1,
    attribute_type: 1,
    define_attribute?: 1,
    migration_types: 1,
    allow_nil?: 1,
    public?: 1,
    identity: 2,
    identity: 3,
    defaults: 1,
    resource: 1,
    field: 2,
    field: 3,
    calculate: 3,
    calculate: 4,
    filter: 1,
    prepare: 1,
    primary?: 1,
    sortable?: 1,
    private_fields: 1,
    policy: 1,
    field_policy: 1,
    authorize_if: 1,
    forbid_if: 1,
    description: 1,
    accept: 1,
    read: 1,
    read: 2,
    update: 1,
    update: 2
  ]

  @header """
  # Generated by bubble_ex from a Bubble app's data model. Deterministic:
  # the same model and name map give the same file.
  #
  # One file holds many modules; split them one per file in your project
  # (lib/my_app/task.ex, ...). The repo is referenced but not generated:
  #   mix igniter.new my_app --install ash,ash_postgres
  # then add these modules and run `mix ash.codegen --dev` while iterating.
  """

  @type option :: {:namespace, String.t()} | {:domain, String.t()} | {:repo, String.t()}

  @doc "Renders `project` as formatted Elixir source."
  @spec render(Project.t(), [option()]) :: {:ok, String.t()} | {:error, Error.t()}
  def render(project, opts \\ [])

  def render(%Project{} = project, opts) when is_list(opts) do
    namespace = Keyword.get(opts, :namespace, "MyApp")
    domain = Keyword.get(opts, :domain, namespace)
    repo = Keyword.get(opts, :repo, namespace <> ".Repo")

    with :ok <- check_alias(:namespace, namespace),
         :ok <- check_alias(:domain, domain),
         :ok <- check_alias(:repo, repo) do
      ctx = %{namespace: namespace, domain: domain, repo: repo}

      modules =
        Enum.map(project.types, &custom_type(&1, ctx)) ++
          Enum.map(project.enums, &enum(&1, ctx)) ++
          Enum.map(project.typed_structs, &typed_struct(&1, ctx)) ++
          keyed_read_module(project, ctx) ++
          Enum.map(project.resources, &resource(&1, ctx)) ++
          [domain_module(project, ctx)] ++ privacy_module(project, ctx)

      source = @header <> "\n" <> Enum.join(modules, "\n\n")

      formatted =
        source
        |> Code.format_string!(locals_without_parens: @locals_without_parens)
        |> IO.iodata_to_binary()

      {:ok, formatted <> "\n"}
    end
  end

  def render(_project, _opts),
    do: {:error, Error.new(:invalid_input, "expected a BubbleEx.Target.Ash.Project")}

  defp check_alias(option, value) do
    if is_binary(value) and Regex.match?(@alias, value),
      do: :ok,
      else:
        {:error, Error.new(:invalid_input, "#{option} must be a module name", %{option => value})}
  end

  # --- modules -------------------------------------------------------------------

  # Any JSON value, stored as jsonb. Its storage type is `:map` (jsonb), but
  # unlike `Ash.Type.Map` it accepts every JSON value, not only objects.
  defp custom_type(%CustomType{kind: :json_value} = type, ctx) do
    """
    defmodule #{module(type.module, ctx)} do
      #{moduledoc(type.description)}use Ash.Type

      @impl Ash.Type
      def storage_type(_constraints), do: :map

      @impl Ash.Type
      def cast_input(value, _constraints), do: if(json?(value), do: {:ok, value}, else: :error)

      @impl Ash.Type
      def cast_stored(value, _constraints), do: {:ok, value}

      @impl Ash.Type
      def dump_to_native(value, _constraints),
        do: if(json?(value), do: {:ok, value}, else: :error)

      defp json?(value) when is_nil(value) or is_boolean(value) or is_number(value), do: true
      defp json?(value) when is_binary(value), do: String.valid?(value)
      defp json?(value) when is_list(value), do: Enum.all?(value, &json?/1)

      defp json?(value) when is_map(value) and not is_struct(value),
        do: Enum.all?(value, fn {k, v} -> (is_binary(k) or is_atom(k)) and json?(v) end)

      defp json?(_value), do: false
    end
    """
  end

  defp enum(enum, ctx) do
    values = Enum.map_join(enum.values, ", ", &enum_value/1)

    """
    defmodule #{module(enum.module, ctx)} do
      #{moduledoc(enum.description)}use Ash.Type.Enum, values: [#{values}]
    #{attribute_lookup(enum)}end
    """
  end

  defp attribute_lookup(%{attributes: []}), do: ""

  # An option set with attributes but no values (WTF-394): Map.fetch!/2 on
  # the empty map is a type warning on Elixir 1.20 (it always raises), so
  # raise the same KeyError explicitly.
  defp attribute_lookup(%{values: []}) do
    """

    @doc "The attribute values of `value`. This option set has no values, so it always raises."
    def attributes(value), do: raise(KeyError, key: value, term: %{})
    """
  end

  defp attribute_lookup(enum) do
    entries =
      Enum.map_join(enum.values, ", ", fn value ->
        fields =
          Enum.map_join(enum.attributes, ", ", fn attribute ->
            key(attribute.name) <> literal(Map.get(value.attributes, attribute.name))
          end)

        literal(value.value) <> " => %{" <> fields <> "}"
      end)

    """

    @attributes %{#{entries}}

    @doc "The attribute values of `value`."
    def attributes(value), do: Map.fetch!(@attributes, value)
    """
  end

  defp enum_value(%{label: nil, value: value}), do: literal(value)

  defp enum_value(%{label: label, value: value}),
    do: "{#{literal(value)}, [label: #{literal(label)}]}"

  defp typed_struct(%TypedStruct{} = struct, ctx) do
    fields = Enum.map_join(struct.fields, "\n", &field(&1, ctx))

    """
    defmodule #{module(struct.module, ctx)} do
      #{moduledoc(struct.description)}use Ash.TypedStruct

      typed_struct do
    #{fields}
      end
    end
    """
  end

  defp field(%Attribute{} = attribute, ctx) do
    options =
      [{"allow_nil?", literal(attribute.allow_nil?)}] ++
        default(attribute) ++ constraints(attribute)

    "field #{atom(attribute.name)}, #{type(attribute.type, ctx)}, #{options(options)}"
  end

  defp resource(%Resource{} = resource, ctx) do
    """
    defmodule #{module(resource.module, ctx)} do
      #{moduledoc(resource.description)}use Ash.Resource, domain: #{ctx.domain}, data_layer: AshPostgres.DataLayer#{authorizers(resource)}

      postgres do
        table #{literal(resource.table)}
        repo #{ctx.repo}
    #{migration_types(resource.migration_types, ctx)}#{references(resource.relationships ++ resource.privacy_relationships)}
      end

      attributes do
    #{Enum.map_join(resource.attributes, "\n", &attribute(&1, ctx))}
      end
    #{relationships(resource.relationships ++ resource.privacy_relationships, ctx)}#{calculations(resource.calculations, ctx)}#{identities(resource.identities)}
      actions do
        defaults #{literal(resource.actions)}
    #{Enum.map_join(resource.extra_actions, "\n", &action(&1, ctx))}
      end
    #{policies(resource, ctx)}#{field_policies(resource.field_policies, ctx)}end
    """
  end

  defp authorizers(%Resource{policies: []}), do: ""
  defp authorizers(%Resource{}), do: ", authorizers: [Ash.Policy.Authorizer]"

  defp action(%Action{type: :read} = action, _ctx) do
    """
    read #{atom(action.name)} do
      #{description(action.description)}#{if action.primary?, do: "\nprimary? true", else: ""}
    end
    """
  end

  defp action(%Action{type: :update} = action, _ctx) do
    """
    update #{atom(action.name)} do
      #{description(action.description)}
      accept [#{Enum.map_join(action.accept, ", ", &atom/1)}]
    end
    """
  end

  defp description(nil), do: ""
  defp description(text), do: "description #{literal(text)}"

  defp calculations([], _ctx), do: ""

  defp calculations(calculations, ctx) do
    lines =
      Enum.map_join(calculations, "\n", fn %Calculation{} = c ->
        options =
          [{"public?", literal(c.public?)}] ++
            if(c.description, do: [{"description", literal(c.description)}], else: []) ++
            if(c.constraints == [], do: [], else: [{"constraints", literal(c.constraints)}])

        "calculate #{atom(c.name)}, #{type(c.type, ctx)}, #{expr(c.expr)}, #{options(options)}"
      end)

    "\ncalculations do\n#{lines}\nend\n"
  end

  @policies_header """
  # Privacy rules compiled from Bubble by bubble_ex (WTF-356).
  # NOT VERIFIED AGAINST BUBBLE: do not ship these policies to users before
  # the replay verification (WTF-384/385) confirms the semantics they rest on.
  # Load the actor with the Privacy module's load_actor/1 on every request
  # and LiveView mount. Enumerate records only through :search; :read
  # returns records by primary key. Field policies do not guard code: a
  # filter, sort or calculation written in code (not *_input) that reads a
  # field the actor may not view still sees its value, so lowered searches
  # must not reference such fields directly, nor the private *_for_privacy
  # relationships. Aggregates (count, min, max, sum, ...) over a field are
  # not covered by field policies either: never aggregate a field the actor
  # may not view.
  """

  defp policies(%Resource{policies: []}, _ctx), do: ""

  defp policies(%Resource{policies: policies}, ctx) do
    "\n" <>
      @policies_header <>
      "policies do\n" <> Enum.map_join(policies, "\n", &policy(&1, ctx)) <> "\nend\n"
  end

  defp policy(%Policy{} = policy, ctx) do
    condition =
      case policy.changing do
        nil ->
          "action(#{atom(policy.action)})"

        names ->
          "[action(#{atom(policy.action)}), changing_attributes([#{Enum.map_join(names, ", ", &atom/1)}])]"
      end

    """
    policy #{condition} do
      #{description(policy.description)}
    #{checks(policy.checks, ctx)}
    end
    """
  end

  defp field_policies([], _ctx), do: ""

  defp field_policies(policies, ctx) do
    body =
      Enum.map_join(policies, "\n", fn %FieldPolicy{} = policy ->
        """
        field_policy [#{Enum.map_join(policy.fields, ", ", &atom/1)}] do
        #{checks(policy.checks, ctx)}
        end
        """
      end)

    "\nfield_policies do\nprivate_fields :hide\n\n" <> body <> "\nend\n"
  end

  defp checks(checks, ctx), do: Enum.map_join(checks, "\n", &check(&1, ctx))

  defp check(%PolicyCheck{kind: kind, test: :always}, _ctx), do: "#{kind} always()"

  defp check(%PolicyCheck{kind: kind, test: :keyed}, ctx),
    do: "#{kind} #{ctx.namespace}.Privacy.KeyedRead"

  defp check(%PolicyCheck{kind: kind, test: {:calculation, name}}, _ctx),
    do: "#{kind} expr(#{identifier!(name)})"

  defp attribute(%Attribute{} = attribute, ctx) do
    options =
      if(attribute.primary_key?, do: [{"primary_key?", "true"}], else: []) ++
        [
          {"allow_nil?", literal(attribute.allow_nil?)},
          {"writable?", literal(attribute.writable?)},
          {"public?", literal(attribute.public?)}
        ] ++ column(attribute) ++ default(attribute) ++ constraints(attribute)

    "attribute #{atom(attribute.name)}, #{type(attribute.type, ctx)}, #{options(options)}"
  end

  defp column(%Attribute{column: nil}), do: []
  defp column(%Attribute{column: column}), do: [{"source", atom(column)}]

  defp default(%Attribute{default: {:value, {:decimal, text}}}) when is_binary(text),
    do: [{"default", "Decimal.new(#{literal(text)})"}]

  defp default(%Attribute{default: {:value, value}}), do: [{"default", literal(value)}]
  defp default(%Attribute{}), do: []

  defp constraints(%Attribute{constraints: []}), do: []
  defp constraints(%Attribute{constraints: c}), do: [{"constraints", literal(c)}]

  defp options(options), do: Enum.map_join(options, ", ", fn {k, v} -> "#{k}: #{v}" end)

  defp migration_types([], _ctx), do: ""

  defp migration_types(types, ctx) do
    entries = Enum.map_join(types, ", ", fn {name, type} -> key(name) <> type(type, ctx) end)
    "\nmigration_types #{entries}\n"
  end

  defp references(relationships) do
    case Enum.filter(relationships, &(&1.db_reference == :ignore)) do
      [] ->
        ""

      ignored ->
        lines = Enum.map_join(ignored, "\n", &"reference #{atom(&1.name)}, ignore?: true")
        "\nreferences do\n#{lines}\nend"
    end
  end

  defp relationships([], _ctx), do: ""

  defp relationships(relationships, ctx) do
    "\nrelationships do\n" <>
      Enum.map_join(relationships, "\n\n", &relationship(&1, ctx)) <> "\nend\n"
  end

  defp relationship(%Relationship{} = r, ctx) do
    """
    #{r.kind} #{atom(r.name)}, #{module(r.destination, ctx)} do
      source_attribute #{atom(r.source_attribute)}
      destination_attribute #{atom(r.destination_attribute)}
      attribute_type #{type(r.attribute_type, ctx)}
      define_attribute? #{literal(r.define_attribute?)}
      allow_nil? #{literal(r.allow_nil?)}
      public? #{literal(r.public?)}#{sortable(r.sortable?)}#{gate(r.gate)}
    end
    """
  end

  # Ash's default (true) is not printed.
  defp sortable(true), do: ""
  defp sortable(false), do: "\nsortable? false"

  defp gate(nil), do: ""
  defp gate(:never), do: "\nfilter expr(false)"

  defp gate({:visible_if, calcs}),
    do: "\nfilter expr(parent(" <> Enum.map_join(calcs, " or ", &identifier!/1) <> "))"

  defp identities([]), do: ""

  defp identities(identities) do
    lines =
      Enum.map_join(identities, "\n", fn identity ->
        "identity #{atom(identity.name)}, [#{Enum.map_join(identity.keys, ", ", &atom/1)}]"
      end)

    "\nidentities do\n#{lines}\nend\n"
  end

  defp domain_module(project, ctx) do
    resources = Enum.map_join(project.resources, "\n", &"resource #{module(&1.module, ctx)}")

    """
    defmodule #{ctx.domain} do
      use Ash.Domain

      resources do
    #{resources}
      end
    end
    """
  end

  # The policy check of every keyed `:read`: the read, or
  # aggregate, selects records by primary key at the top level (`id == x`,
  # `id in [...]`, and-ed with anything), or loads a relationship.
  defp keyed_read_module(project, ctx) do
    if Enum.any?(project.resources, fn r -> Enum.any?(r.extra_actions, & &1.keyed?) end) do
      [
        """
        defmodule #{ctx.namespace}.Privacy.KeyedRead do
          @moduledoc \"\"\"
          Policy check: an authorized read (or aggregate) of the primary `:read`
          must select records by primary key (`Ash.get`) or load them through a
          relationship; direct view in Bubble reaches a record through a
          reference, never by listing. Otherwise it is forbidden. Enumerate
          and count with `:search`.
          Generated by bubble_ex (WTF-356); NOT VERIFIED AGAINST BUBBLE.
          \"\"\"
          use Ash.Policy.SimpleCheck

          alias Ash.Query.{BooleanExpression, Ref}
          alias Ash.Query.Operator.{Eq, In}

          @impl true
          def describe(_opts), do: "the read selects records by primary key"

          # A policy check, not a preparation: it also sees aggregate queries
          # (count, exists, max, ...), which run no read hooks. A
          # relationship load (`accessing_from`) is keyed by the source
          # records' IDs, possibly as `id == parent(...)`.
          @impl true
          def match?(_actor, %{query: %Ash.Query{} = query}, _opts) do
            query.context[:accessing_from] != nil or
              keyed?(query.filter && query.filter.expression, query.resource)
          end

          def match?(_actor, _context, _opts), do: false

          defp keyed?(%BooleanExpression{op: :and, left: left, right: right}, resource),
            do: keyed?(left, resource) or keyed?(right, resource)

          defp keyed?(%Eq{left: %Ref{relationship_path: [], attribute: a}, right: v}, resource),
            do: key?(a, resource) and not Ash.Expr.expr?(v)

          defp keyed?(%Eq{left: v, right: %Ref{relationship_path: [], attribute: a}}, resource),
            do: key?(a, resource) and not Ash.Expr.expr?(v)

          defp keyed?(%In{left: %Ref{relationship_path: [], attribute: a}, right: v}, resource),
            do: key?(a, resource) and not Ash.Expr.expr?(v)

          defp keyed?(_expression, _resource), do: false

          defp key?(attribute, resource),
            do: [name(attribute)] == Ash.Resource.Info.primary_key(resource)

          defp name(%{name: name}), do: name
          defp name(name), do: name
        end
        """
      ]
    else
      []
    end
  end

  # The privacy helpers every generated app needs: whether the policies are
  # verified (never, yet) and loading the actor with what they read.
  # Only with policies (`privacy: :unverified`): an `:omit` Project has none.
  defp privacy_module(%Project{} = project, ctx) do
    if Enum.any?(project.resources, &(&1.policies != [])),
      do: privacy_source(project, ctx),
      else: []
  end

  defp privacy_source(%Project{} = project, ctx) do
    loads = load_tree(project.actor_loads)

    load_actor =
      case Enum.find(project.resources, &(&1.source[:type] == "user")) do
        nil ->
          ""

        user ->
          """

          @doc "The resource of the actor (Bubble's User)."
          def actor_resource, do: #{module(user.module, ctx)}

          @doc \"\"\"
          Reads the actor (a user or a user ID) afresh with `actor_loads/0`,
          bypassing authorization: the policies must see its current values.
          Call it on every request and LiveView mount, never reuse a stored
          actor. Returns nil (logged out) for nil or an unknown ID.
          \"\"\"
          def load_actor(nil), do: nil
          def load_actor(%{id: id}), do: load_actor(id)

          def load_actor(id) when is_binary(id) do
            case Ash.get(#{module(user.module, ctx)}, id, load: actor_loads(), authorize?: false) do
              {:ok, actor} -> actor
              {:error, _} -> nil
            end
          end
          """
      end

    [
      """
      defmodule #{ctx.namespace}.Privacy do
        @moduledoc \"\"\"
        Privacy rules compiled from Bubble to Ash policies by bubble_ex (WTF-356).

        NOT VERIFIED AGAINST BUBBLE. The policies rest on Bubble semantics not
        yet confirmed by replaying the app (WTF-384/385): do not ship them to
        users until they are. See `verified?/0`.
        \"\"\"

        @doc "Whether the generated policies are verified against Bubble: not yet."
        def verified?, do: #{literal(project.policies_verified)}

        @doc "The relationships of the actor that the policies read."
        def actor_loads, do: #{loads}
      #{load_actor}end
      """
    ]
  end

  # [["a", "b"], ["a"], ["c"]] -> "[a: [b: []], c: []]"
  defp load_tree(paths) do
    paths
    |> Enum.reduce(%{}, fn path, tree -> put_in_tree(tree, path) end)
    |> keyword_source()
  end

  defp put_in_tree(tree, []), do: tree

  defp put_in_tree(tree, [key | rest]),
    do: Map.update(tree, key, put_in_tree(%{}, rest), &put_in_tree(&1, rest))

  defp keyword_source(tree) do
    entries =
      tree |> Enum.sort() |> Enum.map_join(", ", fn {k, sub} -> key(k) <> keyword_source(sub) end)

    "[" <> entries <> "]"
  end

  # --- expressions ---------------------------------------------------------------

  @doc """
  Prints a `BubbleEx.Target.Ash.Expr` as `expr(...)` source, e.g.
  `expr(creator_id == ^actor(:id))`. The call needs `require Ash.Expr`
  and `import Ash.Expr` (as inside a resource's `policies` or a query).
  """
  @spec expr(Expr.t()) :: String.t()
  def expr(%Expr{expr: node}), do: "expr(" <> print(node, 0) <> ")"

  # Elixir operator precedence, loosest first: `or`, `and`, `==`/`!=`,
  # ordering, `in`, `+`/`-`, `*`/`/`. A child binding looser than its
  # parent is parenthesized; `not` takes a parenthesized operand unless it
  # is a call or a reference.
  @precedence %{
    or: 1,
    and: 2,
    ==: 3,
    !=: 3,
    >: 4,
    <: 4,
    >=: 4,
    <=: 4,
    in: 5,
    +: 6,
    -: 6,
    *: 7,
    /: 7
  }

  defp print({:or, nodes}, outer),
    do: group(Enum.map_join(nodes, " or ", &print(&1, 1)), 1, outer)

  defp print({:and, nodes}, outer),
    do: group(Enum.map_join(nodes, " and ", &print(&1, 2)), 2, outer)

  defp print({:op, op, left, right}, outer) do
    level = Map.fetch!(@precedence, String.to_existing_atom(op))
    group("#{print(left, level)} #{op} #{print(right, level + 1)}", level, outer)
  end

  defp print({:not, node}, _outer), do: "not " <> print(node, 99)

  defp print({:call, name, args}, _outer) do
    if Regex.match?(@identifier, name),
      do: name <> "(" <> Enum.map_join(args, ", ", &print(&1, 0)) <> ")",
      else: raise(ArgumentError, "invalid function name #{inspect(name)}")
  end

  defp print({:ref, relationships, attribute}, _outer) do
    Enum.each([attribute | relationships], &identifier!/1)
    Enum.join(relationships ++ [attribute], ".")
  end

  defp print({:actor, [name]}, _outer), do: "^actor(#{atom(name)})"

  defp print({:actor, path}, _outer),
    do: "^actor([" <> Enum.map_join(path, ", ", &atom/1) <> "])"

  defp print({:arg, name}, _outer), do: "^arg(#{atom(name)})"
  defp print({:value, value}, _outer), do: literal(value)

  defp group(text, level, outer) when level < outer, do: "(" <> text <> ")"
  defp group(text, _level, _outer), do: text

  defp identifier!(name) do
    if Regex.match?(@identifier, name),
      do: name,
      else: raise(ArgumentError, "invalid reference name #{inspect(name)}")
  end

  # --- printing --------------------------------------------------------------------

  defp moduledoc(nil), do: ""
  defp moduledoc(text), do: "@moduledoc #{literal(text)}\n\n"

  defp module(relative, ctx), do: ctx.namespace <> "." <> relative

  defp type({:array, type}, ctx), do: "{:array, #{type(type, ctx)}}"
  defp type({:module, relative}, ctx), do: module(relative, ctx)
  defp type(atom, _ctx) when is_atom(atom), do: inspect(atom)

  defp atom(name) do
    if Regex.match?(@identifier, name), do: ":" <> name, else: ":" <> literal(name)
  end

  defp key(name) do
    if Regex.match?(@identifier, name), do: name <> ": ", else: literal(name) <> ": "
  end

  defp literal(value), do: inspect(value, limit: :infinity, printable_limit: :infinity)
end
