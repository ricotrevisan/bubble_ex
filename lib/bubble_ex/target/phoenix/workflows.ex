defmodule BubbleEx.Target.Phoenix.Workflows do
  @moduledoc """
  Prints backend workflows bound to Ash (`BubbleEx.Target.Ash.Workflows.Spec`)
  as files of the Phoenix target (WTF-373), for
  `BubbleEx.Target.Phoenix.render/2`'s `workflows:` option. A printer
  only: it reads the spec, never the Model (xref-tested).

  **Generated** (hash-guarded, WTF-359 Q1: entry points):

    * `lib/<app>/workflows/<folder>.ex` - one Ash resource per backend
      folder (`<Module>.Workflows.<Folder>`, no data layer, listed in the
      app's domain) with a generic action per workflow: its arguments, and
      a `run` that calls the body
    * `lib/<app>/workflows/registry.ex` - `<Module>.Workflows.Registry`:
      every workflow's action, parameters, privacy mode and cycle; the
      exposed endpoints; the trigger resources; the privacy bypasses
    * `lib/<app>/workflows/runtime.ex`, `scheduler.ex` (the Oban worker)
      and `triggers.ex` (the database-trigger outbox change, added to each
      trigger resource through `Target.Ash.Source`'s `:extend`)
    * `.wtf/workflows.json` - the name map (pass it back as `names:` to
      `BubbleEx.Target.Ash.Workflows.map/3`), coverage, residue, cycles
      and privacy bypasses

  **Owned** (scaffolded once, Q1: workflow bodies):

    * `lib/<app>/workflows/<folder>/bodies.ex` - one function per
      workflow, `# bubble:workflow <id>` then one `# bubble:step N <type>`
      per action (the `step_order` check); a step without a lowering is a
      `TODO(bubble:<action>)`, and a workflow that reaches one (in its
      body or through a callee) fails before its first step
    * `lib/<app>/bubble/runtime.ex` - the `BubbleEx.Target.Elixir.Runtime`
      contract the compiled values call
    * `test/<app>/bubble_workflows_test.exs` and, with exposed workflows,
      `test/<app>_web/bubble_workflow_api_test.exs`: smoke tests for each
      native workflow (its body and every callee generated whole): it runs
      with empty parameters without raising; a scheduled one also runs as
      a job, a trigger is enqueued by a write of its data type, an exposed
      one answers 503 until the API is served, then its method only. They
      cannot fail on behavior, so they are tagged `bubble_smoke:` and do
      not satisfy the task CLI's `unit_test` check, which needs a
      behavioral test tagged `bubble: "workflow:<id>"`

  Every text from the app (Bubble IDs, names, keys) is printed through
  `inspect/1` or as a sanitized comment; identifiers are the spec's
  validated names.
  """

  alias BubbleEx.CanonicalJson
  alias BubbleEx.Target.Ash.Workflows.Spec

  @identifier ~r/\A[a-z_][a-z0-9_]*\z/
  @module_name ~r/\A[A-Z][A-Za-z0-9]*(\.[A-Z][A-Za-z0-9]*)*\z/

  @doc false
  @spec files(Spec.t(), map()) :: %{
          generated: %{String.t() => String.t()},
          owned: %{String.t() => String.t()},
          extend: map(),
          resources: [String.t()]
        }
  def files(%Spec{} = spec, ctx) do
    lib = "lib/#{ctx.app}/workflows"
    ns = ctx.module

    resources =
      for r <- spec.resources, into: %{} do
        file = Macro.underscore(String.replace_prefix(r.module, "Workflows.", ""))
        {"#{lib}/#{file}.ex", format(resource(r, ns))}
      end

    bodies =
      for r <- spec.resources, into: %{} do
        file = Macro.underscore(String.replace_prefix(r.module, "Workflows.", ""))
        {"#{lib}/#{file}/bodies.ex", format(bodies(r, ns))}
      end

    tests = tests(spec, ctx)

    %{
      generated:
        Map.merge(resources, %{
          "#{lib}/registry.ex" => format(registry(spec, ns)),
          ".wtf/workflows.json" => report(spec)
        }),
      owned: Map.merge(bodies, tests),
      extend: extend(spec, ns),
      resources: Enum.map(spec.resources, &"#{ns}.#{&1.module}")
    }
  end

  # --- resources ---------------------------------------------------------------

  defp resource(r, ns) do
    """
    defmodule #{ns}.#{r.module} do
      @moduledoc #{inspect(folder_doc(r))}
      use Ash.Resource, domain: #{ns}.Domain

      actions do
    #{Enum.map_join(r.actions, "\n", &action(&1, r, ns))}
      end
    end
    """
  end

  defp folder_doc(r) do
    "The backend workflows of Bubble folder #{r.folder || "(none)"}, as generic " <>
      "actions. Generated by bubble_ex (WTF-373): the bodies are in " <>
      "`Bodies` (owned), the parameters are Bubble's (a thing is its Bubble ID)."
  end

  defp action(a, r, ns) do
    args = Enum.map_join(a.arguments, "\n", &argument(&1, ns))

    """
    action #{atom(a.name)}, :term do
      description #{inspect(action_doc(a))}
    #{args}
      run fn input, context -> #{ns}.#{r.module}.Bodies.#{a.name}(input, context) end
    end
    """
  end

  defp action_doc(a) do
    kind =
      case a.kind do
        :api -> "API workflow"
        :custom_event -> "custom event"
        :database_trigger -> "database trigger"
        _ -> "backend workflow"
      end

    name = if a.bubble_name, do: " #{inspect(a.bubble_name)}", else: ""
    "Bubble #{kind}#{name} (#{a.workflow})" <> privacy_doc(a.authorize)
  end

  defp privacy_doc(false),
    do: "; IGNORES PRIVACY RULES in Bubble, so it runs with authorization bypassed"

  defp privacy_doc(:inherit), do: "; runs in its caller's privacy context"
  defp privacy_doc(true), do: ""

  defp argument(arg, ns) do
    "argument #{atom(arg.name)}, #{type(arg.type, ns)}, allow_nil?: true"
  end

  defp type({:array, t}, ns), do: "{:array, #{type(t, ns)}}"
  defp type({:module, m}, ns), do: module("#{ns}.#{m}")
  defp type(t, _ns) when is_atom(t), do: inspect(t)

  # --- registry ------------------------------------------------------------------

  defp registry(spec, ns) do
    actions = Spec.actions(spec)

    workflows =
      Enum.map_join(actions, ",\n", fn a ->
        params = Enum.map_join(a.arguments, ", ", &param_entry(&1, ns))

        "#{inspect(a.workflow)} => %{resource: #{ns}.#{a.module}, action: #{atom(a.name)}, " <>
          "kind: #{inspect(a.kind)}, authorize: #{inspect(a.authorize)}, " <>
          "cycle: #{inspect(a.cycle)}, params: [#{params}]}"
      end)

    endpoints =
      actions
      |> Enum.filter(& &1.exposed)
      |> Enum.uniq_by(& &1.exposed.endpoint)
      |> Enum.map_join(",\n", fn a ->
        e = a.exposed

        "#{inspect(e.endpoint)} => %{workflow: #{inspect(a.workflow)}, auth: #{inspect(e.auth)}, " <>
          "method: #{inspect(e.method)}, return_200?: #{inspect(e.return_200?)}}"
      end)

    triggers =
      Enum.map_join(spec.triggers, ",\n", fn t ->
        "#{ns}.#{t.resource} => #{inspect(t.workflows)}"
      end)

    trigger_types =
      Enum.map_join(spec.triggers, ",\n", fn t ->
        "#{ns}.#{t.resource} => #{inspect(t.data_type)}"
      end)

    trigger_resources =
      Enum.map_join(spec.triggers, ",\n", fn t ->
        "#{inspect(t.data_type)} => #{ns}.#{t.resource}"
      end)

    trigger_fields =
      Enum.map_join(spec.triggers, ",\n", fn t ->
        "#{ns}.#{t.resource} => [" <> Enum.map_join(t.fields, ", ", &atom/1) <> "]"
      end)

    stamps =
      spec.stamps
      |> Enum.sort()
      |> Enum.map_join(",\n", fn {module, s} ->
        "#{ns}.#{module} => %{created: #{maybe_atom(s.created)}, modified: #{maybe_atom(s.modified)}, " <>
          "creator: #{maybe_atom(s.creator)}}"
      end)

    cycles =
      for(c <- spec.cycles, id <- c.bubble_ids, do: {id, c.id})
      |> Enum.sort()
      |> Enum.map_join(",\n", fn {id, cycle} -> "#{inspect(id)} => #{inspect(cycle)}" end)

    lookups = [
      {"workflows", workflows,
       "A workflow by Bubble ID: its resource, action, kind, privacy mode, cycle and parameters.",
       "workflow", "id", "nil"},
      {"endpoints", endpoints, "An exposed workflow by its endpoint name (`/api/1.1/wf/<name>`).",
       "endpoint", "name", "nil"},
      {"triggers", triggers, "The database-trigger workflows of a data resource.", "triggers",
       "resource", "[]"},
      {"trigger_types", trigger_types, "A trigger resource's Bubble data type.", "trigger_type",
       "resource", "nil"},
      {"trigger_resources", trigger_resources, "The resource of a trigger's Bubble data type.",
       "trigger_resource", "type", "nil"},
      {"trigger_fields", trigger_fields,
       "The attributes a trigger resource's job snapshots carry, besides the primary key.",
       "trigger_fields", "resource", "[]"},
      {"stamps", stamps,
       "The attributes Bubble sets itself on a data resource (Created Date, Modified Date, Created By).",
       "stamps", "resource", "%{}"},
      {"cycles", cycles, "The call cycle a workflow is in, or nil.", "cycle", "id", "nil"}
    ]

    """
    defmodule #{ns}.Workflows.Registry do
      @moduledoc #{inspect(registry_doc())}

    #{Enum.map_join(lookups, "\n", &lookup/1)}

      @doc "The workflows that ignore privacy rules in Bubble and run with authorization bypassed."
      def privacy_bypasses, do: #{inspect(spec.privacy_bypasses, limit: :infinity)}
    end
    """
  end

  # A lookup function over a map attribute; with no entries a constant
  # (a lookup in an empty map is a type warning on Elixir 1.20).
  defp lookup({_attr, "", doc, fun, arg, default}) do
    """
    @doc #{inspect(doc)}
    def #{fun}(_#{arg}), do: #{default}
    """
  end

  defp lookup({attr, entries, doc, fun, arg, default}) do
    """
    @#{attr} %{#{entries}}

    @doc #{inspect(doc)}
    def #{fun}(#{arg}), do: Map.get(@#{attr}, #{arg}, #{default})
    """
  end

  defp registry_doc do
    "The lowered backend workflows (WTF-373): generated by bubble_ex from the " <>
      "Bubble app, do not edit. Workflows are keyed by Bubble ID; parameters " <>
      "by their ID, with the name callers use (`key`) and the action argument."
  end

  defp param_entry(arg, ns) do
    resource = if arg.resource, do: "#{ns}.#{arg.resource}", else: "nil"

    "%{id: #{inspect(arg.param)}, key: #{inspect(arg.key)}, argument: #{atom(arg.name)}, " <>
      "kind: #{inspect(arg.kind)}, resource: #{resource}, list?: #{arg.list?}, " <>
      "optional?: #{arg.optional?}}"
  end

  # --- bodies ------------------------------------------------------------------------

  defp bodies(r, ns) do
    """
    defmodule #{ns}.#{r.module}.Bodies do
      @moduledoc #{inspect(bodies_doc(r))}

      alias #{ns}.Workflows.Runtime

    #{Enum.map_join(r.actions, "\n", &body(&1, ns))}
    end
    """
  end

  defp bodies_doc(r) do
    "The bodies of the backend workflows of Bubble folder #{r.folder || "(none)"}. " <>
      "Scaffolded by bubble_ex (WTF-373); this file is yours. Each workflow is marked " <>
      "`# bubble:workflow <id>` with one `# bubble:step N <type>` per Bubble action; " <>
      "a `TODO(bubble:...)` step was not lowered and fails when it runs."
  end

  defp body(a, ns) do
    fun = a.name
    event_todo = event_todo(a)

    steps = Enum.map_join(a.steps, ", ", fn s -> "&#{fun}__step(#{s.index}, &1)" end)
    blocked = Map.get(a, :blocked_by, [])

    blocked_todo =
      if blocked == [],
        do: "",
        else:
          "  # TODO(bubble:#{comment(a.symbol)}) not lowered (here or in a workflow it calls " <>
            "or schedules): it fails before step 1 until every subject is lowered\n"

    condition =
      if a.condition, do: "&#{fun}__condition/1", else: "nil"

    """
    # bubble:workflow #{comment(symbol_part(a.symbol))}
    @doc #{inspect(action_doc(a))}
    def #{fun}(input, context) do
      ctx = Runtime.start(input, context, #{inspect(a.workflow)}, #{inspect(a.authorize)})
    #{event_todo}#{blocked_todo}  Runtime.steps(ctx, #{condition}, [#{steps}], #{inspect(blocked, limit: :infinity)})
    end
    #{condition_fun(a)}#{Enum.map_join(a.steps, "\n", &step(&1, fun, ns))}
    """
  end

  defp event_todo(a) do
    case a.residue do
      [] ->
        ""

      residue ->
        reasons =
          residue |> Enum.map(&Atom.to_string(&1.reason)) |> Enum.uniq() |> Enum.join(", ")

        "  # TODO(bubble:#{comment(a.symbol)}) the event is not lowered: #{reasons}\n"
    end
  end

  defp condition_fun(%{condition: nil}), do: ""

  defp condition_fun(a) do
    """

    # Only when
    defp #{a.name}__condition(#{if Enum.all?(a.condition.bindings, &(&1.bind == :app_version)), do: "_ctx", else: "ctx"}) do
    #{prelude([a.condition])}  #{a.condition.source}
    end
    """
  end

  defp step(%{residue: [_ | _]} = s, fun, _ns) do
    reasons = s.residue |> Enum.map(&Atom.to_string(&1.reason)) |> Enum.uniq() |> Enum.join(", ")

    """

    # bubble:step #{s.index} #{comment(s.type || "unknown")}
    # TODO(bubble:#{comment(s.symbol)}) not lowered: #{reasons}
    defp #{fun}__step(#{s.index}, ctx),
      do: Runtime.not_lowered(ctx, #{inspect(s.bubble_id)}, #{inspect(s.type)})
    """
  end

  defp step(s, fun, ns) do
    call = op(s, ns)
    exprs = [s.condition | op_exprs(s)] |> Enum.reject(&is_nil/1)

    body =
      if s.condition,
        do: "if #{s.condition.source} do\n#{call}\nelse\nRuntime.skip(ctx)\nend",
        else: call

    """

    # bubble:step #{s.index} #{comment(s.type)}
    defp #{fun}__step(#{s.index}, ctx) do
    #{prelude(exprs)}#{body}
    end
    """
  end

  defp op_exprs(%{op: op, args: args}) do
    case op do
      op when op in [:create, :update, :update_current_user, :update_list] ->
        [args[:target] | Enum.map(args.changes, & &1.value)]

      op when op in [:delete, :delete_list] ->
        [args.target]

      op when op in [:schedule, :schedule_list] ->
        [args.at, args.list, args.interval | Enum.map(args.params, & &1.value)]

      :call ->
        Enum.map(args.params, & &1.value)

      :terminate ->
        Enum.map(args.returns, & &1.value)

      :return ->
        if Map.has_key?(args, :values),
          do: Enum.map(args.values, & &1.value),
          else: [args.text, args.content_type]
    end
  end

  defp op(%{op: op, args: args} = s, ns), do: op(op, args, inspect(s.bubble_id), ns)

  defp op(:create, args, id, ns),
    do: "Runtime.create(ctx, #{id}, #{ns}.#{args.resource}, #{changes(args.changes)})"

  defp op(:update, args, id, ns),
    do:
      "Runtime.update(ctx, #{id}, #{ns}.#{args.resource}, #{src(args.target)}, " <>
        "#{changes(args.changes)})"

  defp op(:update_current_user, args, id, ns),
    do:
      "Runtime.update(ctx, #{id}, #{ns}.#{args.resource}, Runtime.actor(ctx, []), " <>
        "#{changes(args.changes)})"

  defp op(:update_list, args, id, ns),
    do:
      "Runtime.update_list(ctx, #{id}, #{ns}.#{args.resource}, #{src(args.target)}, " <>
        "#{changes(args.changes)})"

  defp op(:delete, args, id, _ns), do: "Runtime.delete(ctx, #{id}, #{src(args.target)})"

  defp op(:delete_list, args, id, _ns),
    do: "Runtime.delete_list(ctx, #{id}, #{src(args.target)})"

  defp op(:schedule, args, id, _ns),
    do:
      "Runtime.schedule(ctx, #{id}, #{inspect(args.workflow)}, #{src(args.at)}, " <>
        "#{keyed(args.params, :param)})"

  defp op(:schedule_list, args, id, _ns),
    do:
      "Runtime.schedule_list(ctx, #{id}, #{inspect(args.workflow)}, #{src(args.at)}, " <>
        "#{src(args.list)}, #{src(args.interval)}, #{keyed(args.params, :param)})"

  defp op(:call, args, id, _ns),
    do: "Runtime.call(ctx, #{id}, #{inspect(args.workflow)}, #{keyed(args.params, :param)})"

  defp op(:terminate, args, _id, _ns),
    do: "Runtime.terminate(ctx, #{keyed(args.returns, :return)})"

  defp op(:return, %{values: values}, _id, _ns),
    do: "Runtime.return(ctx, #{keyed(values, :key)})"

  defp op(:return, args, _id, _ns),
    do: "Runtime.return_text(ctx, #{src(args.content_type)}, #{src(args.text)})"

  defp changes(changes) do
    "[" <>
      Enum.map_join(changes, ", ", fn c ->
        "{#{inspect(c.op)}, #{atom(c.attribute)}, #{change_value(c)}}"
      end) <> "]"
  end

  defp change_value(%{op: :clear_list}), do: "nil"
  defp change_value(%{ref: :one, value: v}), do: "Runtime.id(#{src(v)})"

  defp change_value(%{ref: :many, op: op, value: v}) when op in [:add, :remove],
    do: "Runtime.id(#{src(v)})"

  defp change_value(%{ref: :many, value: v}), do: "Runtime.ids(#{src(v)})"
  defp change_value(%{value: v}), do: src(v)

  defp keyed(entries, key) do
    "%{" <>
      Enum.map_join(entries, ", ", fn e -> "#{inspect(Map.fetch!(e, key))} => #{src(e.value)}" end) <>
      "}"
  end

  defp src(nil), do: "nil"
  defp src(%{source: source}), do: "(" <> source <> ")"

  # The variables an expression reads, bound from the context (each once,
  # with the union of the relationship loads its uses need).
  defp prelude(exprs) do
    exprs
    |> Enum.flat_map(& &1.bindings)
    |> Enum.group_by(& &1.var)
    |> Enum.sort()
    |> Enum.map_join(fn {var, [b | _] = bs} ->
      loads = bs |> Enum.flat_map(& &1.loads) |> Enum.uniq() |> Enum.sort()
      "  #{var(var)} = #{binding(b.bind, loads)}\n"
    end)
  end

  defp binding(:actor, loads), do: "Runtime.actor(ctx, #{inspect(loads)})"
  defp binding({:param, id}, loads), do: "Runtime.param(ctx, #{inspect(id)}, #{inspect(loads)})"
  defp binding({:step, id}, loads), do: "Runtime.step(ctx, #{inspect(id)}, #{inspect(loads)})"

  defp binding({:trigger, state}, loads),
    do: "Runtime.trigger(ctx, #{inspect(state)}, #{inspect(loads)})"

  defp binding(:now, _loads), do: "ctx.now"
  defp binding(:app_version, _loads), do: "Runtime.app_version()"

  # --- tests -----------------------------------------------------------------------------

  defp tests(spec, ctx) do
    native = spec |> Spec.actions() |> Enum.filter(&Spec.native?/1)
    triggers = Map.new(spec.triggers, fn t -> {t.data_type, t} end)
    exposed = Enum.filter(native, & &1.exposed)

    scheduler? =
      Enum.any?(
        native,
        &(&1.scheduled? or (&1.kind == :database_trigger and triggers[&1.trigger]))
      )

    aliases = if scheduler?, do: "{Runtime, Scheduler}", else: "Runtime"

    data =
      """
      defmodule #{ctx.module}.BubbleWorkflowsTest do
        # Scaffolded by bubble_ex (WTF-373): smoke tests for each backend
        # workflow whose body (and every workflow it calls or schedules) was
        # generated whole: it runs with empty parameters without raising.
        # They cannot fail on behavior, so they are tagged bubble_smoke and
        # do not satisfy the task CLI's unit_test check: that needs a test
        # asserting the workflow's behavior, tagged bubble: "workflow:<id>".
        use #{ctx.module}.DataCase, async: false
        use Oban.Testing, repo: #{ctx.module}.Repo

        alias #{ctx.module}.Workflows.#{aliases}

        defp ran?({:ok, %{status: status}}), do: status in [:done, :not_run, :terminated, :returned]
        defp ran?({:error, _}), do: true
        defp ran?(_), do: false
      #{Enum.map_join(native, "\n", &workflow_test(&1, triggers, ctx))}
      end
      """

    api =
      if exposed == [] do
        %{}
      else
        %{
          "test/#{ctx.app}_web/bubble_workflow_api_test.exs" =>
            format("""
            defmodule #{ctx.web}.BubbleWorkflowApiTest do
              # Scaffolded by bubble_ex (WTF-373): each exposed workflow whose
              # body was generated whole answers at /api/1.1/wf/<name>, once
              # the workflow API is served, and only to its HTTP method.
              # Smoke tests: tagged bubble_smoke, they do not satisfy the task
              # CLI's unit_test check, which needs a behavioral test tagged
              # bubble: "workflow:<id>".
              use #{ctx.web}.ConnCase, async: false

              defp serve_api do
                config = Application.get_env(:#{ctx.app}, #{ctx.module}.Workflows, [])
                Application.put_env(:#{ctx.app}, #{ctx.module}.Workflows, Keyword.put(config, :serve_workflow_api, true))
                on_exit(fn -> Application.put_env(:#{ctx.app}, #{ctx.module}.Workflows, config) end)
              end

            #{Enum.map_join(exposed, "\n", &api_test/1)}
            end
            """)
        }
      end

    Map.put(api, "test/#{ctx.app}/bubble_workflows_test.exs", format(data))
  end

  defp workflow_test(a, triggers, ctx) do
    tag = inspect(a.symbol)

    run = """

    @tag bubble_smoke: #{tag}
    test #{inspect("workflow #{a.workflow} runs with empty parameters")} do
      assert ran?(Runtime.run(#{inspect(a.workflow)}, %{}))
    end
    """

    scheduled =
      if a.scheduled? do
        """

        @tag bubble_smoke: #{tag}
        test #{inspect("workflow #{a.workflow} runs as a scheduled job")} do
          result = perform_job(Scheduler, %{"workflow" => #{inspect(a.workflow)}, "params" => %{}})
          assert result == :ok or match?({:error, _}, result)
        end
        """
      else
        ""
      end

    trigger =
      case a.kind == :database_trigger && triggers[a.trigger] do
        %{resource: resource} ->
          """

          @tag bubble_smoke: #{tag}
          test #{inspect("workflow #{a.workflow} is enqueued by a write of its data type")} do
            {:ok, _} = Ash.create(#{ctx.module}.#{resource}, %{id: Runtime.new_id()}, authorize?: false)
            assert_enqueued(worker: Scheduler, args: %{"workflow" => #{inspect(a.workflow)}})
          end
          """

        _ ->
          ""
      end

    run <> scheduled <> trigger
  end

  defp api_test(a) do
    {method, other} = if a.exposed.method == :get, do: {"get", "post"}, else: {"post", "get"}

    """
    @tag bubble_smoke: #{inspect(a.symbol)}
    test #{inspect("workflow #{a.workflow} answers at its endpoint only when served")}, %{conn: conn} do
      path = "/api/1.1/wf/" <> URI.encode(#{inspect(a.exposed.endpoint)}, &URI.char_unreserved?/1)
      assert #{method}(conn, path, %{}).status == 503

      serve_api()
      assert #{method}(build_conn(), path, %{}).status in [200, 400, 401]
      assert #{other}(build_conn(), path, %{}).status == 405
    end
    """
  end

  # --- extend, report ---------------------------------------------------------------------

  defp extend(spec, ns) do
    for t <- spec.triggers, into: %{} do
      {t.resource,
       %{
         dsl: """
           changes do
             change #{ns}.Workflows.Triggers, on: [:create, :update, :destroy]
           end
         """
       }}
    end
  end

  defp report(spec) do
    residue =
      for r <- Spec.residue(spec),
          do: %{"subject" => r.subject, "reason" => Atom.to_string(r.reason)}

    %{
      "version" => 1,
      "names" => spec.names,
      "coverage" => Spec.coverage(spec),
      "privacy_bypasses" => spec.privacy_bypasses,
      "cycles" =>
        Enum.map(
          spec.cycles,
          &%{"id" => &1.id, "workflows" => &1.workflows, "synchronous" => &1.synchronous}
        ),
      "residue" => residue
    }
    |> CanonicalJson.ordered()
    |> Jason.encode!(pretty: true)
    |> Kernel.<>("\n")
  end

  # --- printing helpers ----------------------------------------------------------------

  defp atom(name) do
    if Regex.match?(@identifier, name),
      do: ":" <> name,
      else: raise(ArgumentError, "not an identifier: #{inspect(name)}")
  end

  defp maybe_atom(nil), do: "nil"
  defp maybe_atom(name), do: atom(name)

  defp var(name) do
    if Regex.match?(@identifier, name),
      do: name,
      else: raise(ArgumentError, "not a variable name: #{inspect(name)}")
  end

  defp module(name) do
    if Regex.match?(@module_name, name),
      do: name,
      else: raise(ArgumentError, "not a module name: #{inspect(name)}")
  end

  # The part of an index symbol ID after its kind (`workflow:` / `action:`),
  # as the task CLI's step markers name it.
  defp symbol_part(id), do: id |> String.split(":", parts: 2) |> List.last()

  # App text in a comment: one line, no control characters.
  defp comment(text) do
    text
    |> to_string()
    |> String.replace(~r/[\x00-\x1f\x7f\x{85}\x{2028}\x{2029}]/u, "?")
  end

  # Ash's DSL without parentheses, as Ash's formatter prints it.
  @locals_without_parens [action: 2, action: 3, argument: 2, argument: 3, description: 1, run: 1]

  defp format(source),
    do:
      source
      |> Code.format_string!(locals_without_parens: @locals_without_parens)
      |> IO.iodata_to_binary()
      |> Kernel.<>("\n")
end
